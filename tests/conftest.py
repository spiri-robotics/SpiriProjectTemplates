def generate(dest: Path, **answers) -> Path:
    """Generate a project from this checkout into *dest*."""
    copier.run_copy(
        str(TEMPLATE_ROOT),
        dest,
        data={**BASE_ANSWERS, **answers},
        defaults=True,
        unsafe=True,
        quiet=True,
        vcs_ref="HEAD",
    )
    return dest


def run(cmd: list[str], cwd: Path, **kwargs) -> subprocess.CompletedProcess:
    """Run *cmd* in a generated project, outside this repo's virtualenv."""
    env = {
        k: v for k, v in os.environ.items() if k not in ("VIRTUAL_ENV", "UV_PROJECT_ENVIRONMENT")
    }
    result = subprocess.run(
        cmd, check=False, cwd=cwd, env=env, capture_output=True, text=True, **kwargs
    )
    assert result.returncode == 0, (
        f"{' '.join(cmd)} failed in {cwd}:\n{result.stdout}\n{result.stderr}"
    )
    return result


